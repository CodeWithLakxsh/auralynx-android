#!/usr/bin/env python3
"""
License audit for the app's release runtime classpath.

Resolves every artifact Gradle ships in the release APK, reads its declared license from the
Maven POM (following <parent> POMs), writes docs/DEPENDENCY_LICENSES.md and exits non-zero if any
dependency has a license that is not known to be compatible with GPL-3.0-or-later.

Usage: python3 scripts/check_licenses.py   (run from the repository root after a Gradle sync)
"""
import os, re, subprocess, sys, glob, urllib.request, xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.expanduser(os.environ.get("GRADLE_USER_HOME", "~/.gradle")) + "/caches/modules-2/files-2.1"

# Licenses compatible with distributing the combined work under GPL-3.0-or-later.
ALLOWED = [
    (re.compile(r"apache.*2", re.I), "Apache-2.0"),
    (re.compile(r"\bmit\b", re.I), "MIT"),
    (re.compile(r"bsd", re.I), "BSD"),
    (re.compile(r"gnu general public license.*3|gpl-?3", re.I), "GPL-3.0"),
]

def resolve():
    out = subprocess.run([os.path.join(ROOT, "gradlew"), "-q", ":app:dependencies", "--configuration", "releaseRuntimeClasspath"],
                         cwd=ROOT, capture_output=True, text=True, check=True).stdout
    coords = set()
    for line in out.splitlines():
        m = re.search(r"--- ([\w.\-]+):([\w.\-]+):([\w.\-]+)(?: -> ([\w.\-]+))?", line)
        if m and not line.strip().endswith("(c)"):
            g, a, v, forced = m.groups()
            coords.add((g, a, forced or v))
    return sorted(coords)

def pom_path(g, a, v):
    hits = glob.glob(f"{CACHE}/{g}/{a}/{v}/*/{a}-{v}.pom")
    return hits[0] if hits else None

REPOS = ["https://dl.google.com/dl/android/maven2", "https://repo1.maven.org/maven2"]

def load_pom(g, a, v):
    """POM from the Gradle cache, or downloaded from Google Maven / Maven Central."""
    p = pom_path(g, a, v)
    if p:
        return ET.parse(p).getroot()
    for repo in REPOS:
        url = f"{repo}/{g.replace('.', '/')}/{a}/{v}/{a}-{v}.pom"
        try:
            with urllib.request.urlopen(url, timeout=20) as r:
                return ET.fromstring(r.read())
        except Exception:
            continue
    return None

def licenses(g, a, v, depth=0):
    root = load_pom(g, a, v)
    if root is None or depth > 4:
        return []
    # Old POMs omit the Maven XML namespace, so match on the local tag name.
    local = lambda e: e.tag.rsplit("}", 1)[-1]
    found = [next((c.text or "").strip() for c in l if local(c) == "name") if any(local(c) == "name" for c in l) else ""
             for l in root.iter() if local(l) == "license"]
    found = [f for f in found if f]
    if found:
        return found
    parent = next((e for e in root if local(e) == "parent"), None)
    if parent is not None:
        field = lambda n: next((c.text for c in parent if local(c) == n), None)
        return licenses(field("groupId"), field("artifactId"), field("version"), depth + 1)
    return []

def classify(names):
    for n in names:
        for rx, spdx in ALLOWED:
            if rx.search(n):
                return spdx
    return None

def main():
    rows, problems = [], []
    for g, a, v in resolve():
        names = licenses(g, a, v)
        spdx = classify(names)
        rows.append((f"{g}:{a}:{v}", ", ".join(names) or "NOT DECLARED", spdx or "REVIEW"))
        if spdx is None:
            problems.append(f"{g}:{a}:{v} -> {names or 'no license in POM'}")
    md = ["# Dependency licenses", "",
          "Generated by `scripts/check_licenses.py` from the release runtime classpath (what ships in the APK).",
          "Every entry must be compatible with GPL-3.0-or-later.", "",
          f"Total artifacts: {len(rows)}", "", "| Artifact | Declared license | Classified |", "|---|---|---|"]
    md += [f"| `{c}` | {n} | {s} |" for c, n, s in rows]
    with open(os.path.join(ROOT, "docs", "DEPENDENCY_LICENSES.md"), "w") as f:
        f.write("\n".join(md) + "\n")
    counts = {}
    for _, _, s in rows:
        counts[s] = counts.get(s, 0) + 1
    print(f"{len(rows)} artifacts: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    if problems:
        print("Needs review:\n  " + "\n  ".join(problems))
        sys.exit(1)

if __name__ == "__main__":
    main()
